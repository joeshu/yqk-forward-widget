"""Generate the Foundation capability constants from the runtime registry."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def render():
    data=json.loads((ROOT/'Plugins/media-capabilities.json').read_text())
    lines=['// Generated by Scripts/generate_media_capabilities.py; do not hand edit.', '#import <Foundation/Foundation.h>', '']
    for key in ('networkTransports','cicadaFormats','avFormats','unsupportedContainers','unsupportedVideoCodecs'):
        values=','.join('@'+json.dumps(x) for x in data[key])
        lines.append('static inline NSArray<NSString *> *MediaCapability%s(void) {return @[%s];}' % (key[0].upper()+key[1:],values))
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    target=ROOT/'Sources/MediaCapabilityRegistry.h';result=render()
    if args.check:
        if not target.exists() or target.read_text()!=result:raise SystemExit('Stale media capability registry')
    else:target.write_text(result)
