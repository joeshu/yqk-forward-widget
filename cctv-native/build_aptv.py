"""Build a single-file APTV service; no Node/process imports at runtime."""
import argparse
import ast
import base64
from pathlib import Path
import zlib

HERE = Path(__file__).resolve().parent
# Bump this for each published snapshot; the unversioned file remains a compatibility alias.
VERSION = '0.1.0'


def render():
    original = (HERE/'service.py').read_text()
    original = original.replace('RUNTIME_BUNDLE = None', 'RUNTIME_BUNDLE = '+repr(base64.b85encode((HERE/'vendor/cctv-live-worker-ad9fd2d18801.js.zlib').read_bytes())), 1)
    tree = ast.parse(original)
    lines = original.splitlines(keepends=True)
    excluded = {'Engine', 'setup', 'cache_paths', 'main'}
    for node in reversed(tree.body):
        remove = isinstance(node, (ast.ClassDef, ast.FunctionDef)) and node.name in excluded
        remove |= isinstance(node, ast.Import) and any(a.name in ('subprocess','signal','shutil') for a in node.names)
        remove |= isinstance(node, ast.ImportFrom) and node.module in ('__future__', 'cctv_native_ts')
        remove |= isinstance(node, ast.If) and ast.get_source_segment(original,node.test) == "__name__ == '__main__'"
        if remove:
            del lines[node.lineno-1:node.end_lineno]
    service = ''.join(lines)
    # Shared HTTP/media code is unchanged. Only platform engine/bootstrap differ.
    service = service.replace('"mode": "official-runtime-original-ts"', '"mode": "jscore-original-ts"')
    service = service.replace("'mode': 'official-runtime-original-ts'", "'mode': 'jscore-original-ts'")
    assets = {
        'JSCORE_HOST': 'jscore-host.js', 'JSCORE_BOOT': 'jscore-boot.js',
        'JSCORE_TRANSFORM': 'jscore-transform.js',
        'IDB_SOURCE': 'vendor/fake-indexeddb-6.2.6.js',
    }
    def compressed(value):
        return repr(base64.b85encode(zlib.compress(value.encode(),9)))
    helper = (HERE/'cctv_native_ts.py').read_text().replace('from __future__ import annotations\n', '', 1)
    license_text = (HERE/'vendor/fake-indexeddb-LICENSE').read_text()
    prefix = ('#!/usr/bin/env python3\nfrom __future__ import annotations\n'
        '# Generated by cctv-native/build_aptv.py. Static Python entry for embedded runners.\n'
        '# Includes fake-indexeddb 6.2.6, Copyright 2017 Jeremy Scheff, Apache-2.0.\n'
        'import base64 as _b64, zlib as _zlib\n'
        'def _unpack(value): return _zlib.decompress(_b64.b85decode(value)).decode("utf-8")\n'
        'THIRD_PARTY_LICENSE = '+repr(license_text)+'\n')
    # Only JavaScript data is packed. Python declarations, imports and the
    # __main__/start entry points must be visible to embedded host scanners.
    payload = helper+'\n'+service+'\n'
    payload += '\n'.join(k+' = _unpack('+compressed((HERE/v).read_text())+')'
                         for k,v in assets.items())+'\n'
    payload += (HERE/'jscore_engine.py').read_text()+'\n'
    payload += (HERE/'aptv_epg.py').read_text()+'\n'
    payload += (HERE/'aptv_prefetch.py').read_text()+'\n'
    payload += (HERE/'aptv_channels.py').read_text()+'\n'
    payload += (HERE/'aptv_main.py').read_text()
    return prefix+payload


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = render()
    targets = (HERE/'cctv-aptv.py', HERE/('cctv-aptv-v'+VERSION+'.py'))
    if args.check:
        stale = [target.name for target in targets
                 if not target.exists() or target.read_text()!=content]
        if stale:
            raise SystemExit('APTV standalone files are out of date: '+', '.join(stale))
    else:
        for target in targets:
            target.write_text(content)
