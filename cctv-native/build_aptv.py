"""Build a single-file APTV service; no Node/process imports at runtime."""
import argparse
import ast
import base64
from pathlib import Path
import zlib

HERE = Path(__file__).resolve().parent


def render():
    original = (HERE/'service.py').read_text()
    tree = ast.parse(original)
    lines = original.splitlines(keepends=True)
    excluded = {'Engine', 'setup', 'cache_paths', 'main'}
    for node in reversed(tree.body):
        remove = isinstance(node, (ast.ClassDef, ast.FunctionDef)) and node.name in excluded
        remove |= isinstance(node, ast.Import) and any(a.name in ('subprocess','signal','shutil') for a in node.names)
        remove |= isinstance(node, ast.ImportFrom) and node.module == '__future__'
        remove |= isinstance(node, ast.If) and ast.get_source_segment(original,node.test) == "__name__ == '__main__'"
        if remove:
            del lines[node.lineno-1:node.end_lineno]
    service = ''.join(lines)
    # Shared HTTP/media code is unchanged. Only platform engine/bootstrap differ.
    service = service.replace('"mode": "official-runtime-original-ts"', '"mode": "jscore-original-ts"')
    service = service.replace("'mode': 'official-runtime-original-ts'", "'mode': 'jscore-original-ts'")
    assets = {
        'JSCORE_HOST': 'jscore-host.js', 'JSCORE_BOOT': 'jscore-boot.js',
        'JSCORE_TRANSFORM': 'jscore-transform.js',
        'IDB_SOURCE': 'vendor/fake-indexeddb-6.2.6.js',
    }
    payload = service+'\n'
    payload += '\n'.join(k+' = '+repr((HERE/v).read_text()) for k,v in assets.items())+'\n'
    payload += (HERE/'jscore_engine.py').read_text()+'\n'
    payload += (HERE/'aptv_main.py').read_text()
    helper = (HERE/'cctv_native_ts.py').read_text()
    license_text = (HERE/'vendor/fake-indexeddb-LICENSE').read_text()
    def compressed(value):
        return repr(base64.b85encode(zlib.compress(value.encode(),9)))
    return ('#!/usr/bin/env python3\nfrom __future__ import annotations\n'
        '# Generated by cctv-native/build_aptv.py. In-process system JavaScriptCore.\n'
        '# Includes fake-indexeddb 6.2.6, Copyright 2017 Jeremy Scheff, Apache-2.0.\n'
        '# License: https://github.com/joeshu/yqk-forward-widget/blob/main/cctv-native/vendor/fake-indexeddb-LICENSE\n'
        'import base64 as _b64, zlib as _zlib, sys as _sys, types as _types\n'
        'def _unpack(value): return _zlib.decompress(_b64.b85decode(value)).decode("utf-8")\n'
        'THIRD_PARTY_LICENSE = '+repr(license_text)+'\n'
        '_helper = _types.ModuleType("cctv_native_ts")\n'
        '_sys.modules["cctv_native_ts"] = _helper\n'
        'exec(compile(_unpack('+compressed(helper)+'), "<cctv_native_ts>", "exec"), _helper.__dict__)\n'
        'exec(compile(_unpack('+compressed(payload)+'), "<cctv_aptv>", "exec"), globals())\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = HERE.parent/'cctv-aptv.py'
    content = render()
    if args.check:
        if not target.exists() or target.read_text()!=content:
            raise SystemExit('APTV standalone file is out of date')
    else:
        target.write_text(content)
